select NombreEstudiante,enero,febrero,marzo,abril,mayo,junio,julio,agosto,septiembre,octubre,idalumno from pagos
inner join alumno ON pagos.idalumno = alumno.id 
ORDER BY CASE
	WHEN grado = 'Primero Básico' THEN 1
	WHEN grado = 'Segundo Básico' THEN 2
	WHEN grado = 'Tercero Básico' THEN 3
	WHEN grado = 'Cuarto Bachillerato' THEN 4
	WHEN grado = 'Quinto Bachillerato' THEN 5
ELSE 1000 END asc,
ApellidoEstudiante asc;
